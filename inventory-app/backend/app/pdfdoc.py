"""Server-side PDF documents (purchase orders, sales orders, packing slips, labels, reports) with reportlab.

Standard PDF fonts have no rupee glyph, so amounts print as 'INR 1,23,456.00'."""
import io
from decimal import Decimal
from typing import Optional, Sequence

from reportlab.lib import colors
from reportlab.lib.pagesizes import A4, landscape
from reportlab.lib.styles import ParagraphStyle, getSampleStyleSheet
from reportlab.lib.units import mm
from reportlab.platypus import Paragraph, SimpleDocTemplate, Spacer, Table, TableStyle

TEAL = colors.HexColor("#0f766e")
GREY = colors.HexColor("#64748b")
LINE = colors.HexColor("#e2e8f0")


def inr(x) -> str:
    """Indian digit grouping: 1234567.5 -> 'INR 12,34,567.50'."""
    n = Decimal(str(x or 0)).quantize(Decimal("0.01"))
    sign = "-" if n < 0 else ""
    whole, frac = f"{abs(n):.2f}".split(".")
    head, tail = whole[:-3], whole[-3:]
    if head:
        head = ",".join([head[max(i - 2, 0):i] for i in range(len(head), 0, -2)][::-1])
        whole = head + "," + tail
    return f"{sign}INR {whole}.{frac}"


def _p(text, style):
    return Paragraph(str(text if text is not None else "").replace("&", "&amp;").replace("<", "&lt;").replace("\n", "<br/>"), style)


def build_pdf(*, title: str, org: dict, meta: Sequence[tuple[str, str]], parties: Sequence[tuple[str, Sequence[str]]],
              columns: Sequence[str], rows: Sequence[Sequence], col_widths: Sequence[float], right_cols: Sequence[int] = (),
              totals: Sequence[tuple[str, str]] = (), notes: Optional[str] = None, footer: Optional[str] = None,
              landscape_mode: bool = False) -> bytes:
    buf = io.BytesIO()
    size = landscape(A4) if landscape_mode else A4
    doc = SimpleDocTemplate(buf, pagesize=size, leftMargin=15 * mm, rightMargin=15 * mm, topMargin=14 * mm, bottomMargin=16 * mm,
                            title=f"{title} {meta[0][1] if meta else ''}", author=org.get("name", ""))
    ss = getSampleStyleSheet()
    h = ParagraphStyle("h", parent=ss["Normal"], fontName="Helvetica-Bold", fontSize=18, textColor=TEAL, leading=22)
    org_s = ParagraphStyle("o", parent=ss["Normal"], fontName="Helvetica-Bold", fontSize=11, leading=14)
    sm = ParagraphStyle("sm", parent=ss["Normal"], fontSize=8.5, leading=11, textColor=GREY)
    body = ParagraphStyle("b", parent=ss["Normal"], fontSize=8.5, leading=11)
    bold = ParagraphStyle("bb", parent=body, fontName="Helvetica-Bold")
    story = []
    head = Table([[[_p(org.get("name", ""), org_s), _p("\n".join(x for x in [org.get("address"), org.get("state"), f"GSTIN: {org['gstin']}" if org.get("gstin") else None] if x), sm)],
                   [_p(title.upper(), h)]]], colWidths=[None, 70 * mm])
    head.setStyle(TableStyle([("VALIGN", (0, 0), (-1, -1), "TOP"), ("ALIGN", (1, 0), (1, 0), "RIGHT")]))
    story += [head, Spacer(1, 6)]
    # meta + parties
    left = [[_p(k, sm), _p(v, bold)] for k, v in meta]
    mt = Table(left, colWidths=[28 * mm, 45 * mm]); mt.setStyle(TableStyle([("TOPPADDING", (0, 0), (-1, -1), 1), ("BOTTOMPADDING", (0, 0), (-1, -1), 1), ("LEFTPADDING", (0, 0), (-1, -1), 0)]))
    cells = [mt] + [[_p(hd, sm)] + [_p(x, body) for x in lines_] for hd, lines_ in parties]
    pt = Table([cells], colWidths=[75 * mm] + [(size[0] - 30 * mm - 75 * mm) / max(1, len(parties))] * len(parties))
    pt.setStyle(TableStyle([("VALIGN", (0, 0), (-1, -1), "TOP"), ("LEFTPADDING", (0, 0), (-1, -1), 0)]))
    story += [pt, Spacer(1, 8)]
    # lines
    data = [[_p(c, ParagraphStyle("th", parent=bold, textColor=colors.white)) for c in columns]]
    for r in rows:
        data.append([_p(c, body) for c in r])
    t = Table(data, colWidths=[w * mm for w in col_widths], repeatRows=1)
    st = [("BACKGROUND", (0, 0), (-1, 0), TEAL), ("VALIGN", (0, 0), (-1, -1), "TOP"), ("LINEBELOW", (0, 1), (-1, -1), 0.25, LINE),
          ("TOPPADDING", (0, 0), (-1, -1), 4), ("BOTTOMPADDING", (0, 0), (-1, -1), 4), ("ROWBACKGROUNDS", (0, 1), (-1, -1), [colors.white, colors.HexColor("#f8fafc")])]
    for c in right_cols:
        st.append(("ALIGN", (c, 0), (c, -1), "RIGHT"))
    t.setStyle(TableStyle(st))
    story.append(t)
    if totals:
        tt = Table([[_p(k, bold if i == len(totals) - 1 else body), _p(v, bold if i == len(totals) - 1 else body)] for i, (k, v) in enumerate(totals)], colWidths=[40 * mm, 38 * mm], hAlign="RIGHT")
        tt.setStyle(TableStyle([("ALIGN", (1, 0), (1, -1), "RIGHT"), ("LINEABOVE", (0, len(totals) - 1), (-1, len(totals) - 1), 0.75, TEAL), ("TOPPADDING", (0, 0), (-1, -1), 2), ("BOTTOMPADDING", (0, 0), (-1, -1), 2)]))
        story += [Spacer(1, 8), tt]
    if notes:
        story += [Spacer(1, 10), _p("Notes", sm), _p(notes, body)]

    def foot(canvas, d):
        canvas.saveState(); canvas.setFont("Helvetica", 7.5); canvas.setFillColor(GREY)
        canvas.drawString(15 * mm, 9 * mm, footer or "Generated by StockPilot")
        canvas.drawRightString(size[0] - 15 * mm, 9 * mm, f"Page {d.page}")
        canvas.restoreState()

    doc.build(story, onFirstPage=foot, onLaterPages=foot)
    return buf.getvalue()
